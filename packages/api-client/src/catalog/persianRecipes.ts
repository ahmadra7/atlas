type Line = {
  name: string;
  quantity?: string | null;
  unit?: string | null;
  optional?: boolean;
};

type StepDraft = {
  instruction: string;
  tip?: string;
  timerSeconds?: number | null;
};

function line(name: string, quantity?: string | null, unit?: string | null, optional?: boolean): Line {
  return { name, quantity: quantity ?? null, unit: unit ?? null, optional };
}

function toIng(item: Line): RecipeIngredient {
  return {
    ingredientId: ingredientIdFromName(item.name),
    name: item.name,
    quantity: item.quantity ?? null,
    unit: item.unit ?? null,
    optional: item.optional,
  };
}

function toSteps(slug: string, imageUrl: string, drafts: StepDraft[]): RecipeStep[] {
  return drafts.map((step, index) => ({
    id: `step-${slug}-${index + 1}`,
    order: index + 1,
    instruction: step.instruction,
    tip: step.tip ?? null,
    timerSeconds: step.timerSeconds ?? null,
    imageUrl,
  }));
}

function recipe(input: {
  slug: string;
  title: string;
  description: string;
  category: string;
  meal: MealType;
  difficulty: Difficulty;
  prepMinutes: number;
  cookMinutes: number;
  servings: number;
  imageUrl: string;
  dietaryTags?: string[];
  budgetFriendly?: boolean;
  region?: string;
  ingredients: Line[];
  steps: StepDraft[];
}): Recipe {
  return {
    id: `rec-${input.slug}`,
    slug: input.slug,
    title: input.title,
    description: input.description,
    category: input.category,
    meal: input.meal,
    cuisine: "ایرانی",
    region: input.region ?? "ایران",
    difficulty: input.difficulty,
    prepMinutes: input.prepMinutes,
    cookMinutes: input.cookMinutes,
    totalMinutes: input.prepMinutes + input.cookMinutes,
    servings: input.servings,
    imageUrl: input.imageUrl,
    dietaryTags: input.dietaryTags ?? [],
    budgetFriendly: input.budgetFriendly ?? true,
    versionId: `rv-${input.slug}-1`,
    ingredients: input.ingredients.map(toIng),
    steps: toSteps(input.slug, input.imageUrl, input.steps),
  };
}

